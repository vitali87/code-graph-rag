#!/usr/bin/env python3
"""Write rust/cgr_graph_rs/src/formats/charsets.rs from Python's codecs.

expat reads six encodings itself; for any other name, Python's pyexpat asks
the codec of that name to decode each of the 256 bytes on its own, and uses
what comes back as a single-byte table (a byte it cannot decode alone is not
a character). The Rust XML reader does the same from these tables, so a
project file in, say, windows-1251 reads exactly as it did through Python.

Kept: every codec whose lower half is ASCII (a UTF-8 or ASCII alias keeps
only ASCII, as it does in expat). Left out: EBCDIC codecs, whose XML
declaration expat could not have read, and codecs whose single bytes decode
to more or fewer than 256 characters, which pyexpat refuses.

Run it (stdlib only) with the newest Python cgr supports, so the tables carry
its corrections: Python 3.13 mapped palmos 0x9B to U+203A, which 3.12 left
as U+009B. codebase_rag/tests/test_safe_xml.py checks the result against the
Python running the suite, allowing only that known older mapping.
"""

from __future__ import annotations

import codecs
import encodings
import encodings.aliases
import pkgutil
import warnings
from pathlib import Path

OUTPUT = (
    Path(__file__).resolve().parents[1]
    / "rust"
    / "cgr_graph_rs"
    / "src"
    / "formats"
    / "charsets.rs"
)
NOT_A_CHARACTER = "�"


def single_byte_table(codec: str) -> tuple[int, ...] | None:
    try:
        codecs.lookup(codec)
        # unicode_escape warns about the backslashes among the 256 bytes.
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", DeprecationWarning)
            text = bytes(range(256)).decode(codec, "replace")
    except (LookupError, UnicodeError, TypeError, ValueError):
        return None
    if len(text) != 256 or text[:128] != "".join(map(chr, range(128))):
        return None
    return tuple(0 if c == NOT_A_CHARACTER else ord(c) for c in text[128:])


def main() -> None:
    modules = sorted(
        {m.name for m in pkgutil.iter_modules(encodings.__path__)} - {"aliases"}
    )
    tables: dict[tuple[int, ...], int] = {}
    names: dict[str, int] = {}
    for module in modules:
        table = single_byte_table(module)
        if table is None or max(table) > 0xFFFF:
            continue
        index = tables.setdefault(table, len(tables))
        names[module] = index
        for alias, target in encodings.aliases.aliases.items():
            # A few aliases are spelled with capitals Python's own lookup
            # never produces, so no declaration reaches them.
            if target == module and alias == alias.lower():
                names[alias] = index

    lines = [
        "//! Single-byte tables for the encodings expat reads through Python's",
        "//! codecs: each codec's characters for bytes 0x80 to 0xFF, 0 where a",
        "//! byte is not a character on its own. Generated by",
        "//! scripts/generate_xml_charsets.py; do not edit.",
        "",
        "/// Python's normalised codec names and aliases, sorted, to a table.",
        "pub const NAMES: &[(&str, usize)] = &[",
    ]
    lines += [f'    ("{name}", {index}),' for name, index in sorted(names.items())]
    lines += ["];", "", "pub const TABLES: &[[u16; 128]] = &["]
    for table in sorted(tables, key=tables.__getitem__):
        lines.append("    [")
        for row in range(0, 128, 8):
            cells = ", ".join(f"0x{code:04X}" for code in table[row : row + 8])
            lines.append(f"        {cells},")
        lines.append("    ],")
    lines.append("];")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
