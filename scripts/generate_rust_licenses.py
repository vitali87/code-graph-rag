#!/usr/bin/env python3
"""Write the licences of the Rust crates compiled into cgr-graph-rs.

The extension's wheel is one shared library with every crate it depends on
compiled in, so it owes each crate's copyright notice and licence text, as
the PyInstaller binaries do for theirs. The file ships in the wheel's
`.dist-info/licenses`, where `generate_third_party_notices.py` reads it for
the binaries too.

Only crates linked into the library count: procedural macros and build
scripts run while compiling and ship nothing. `--check` fails when the file
no longer matches `Cargo.lock`, so a dependency change cannot ship without
its notice.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess  # nosec B404 - runs cargo, a fixed argument list
import sys
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
CRATE_DIR = REPO_ROOT / "rust" / "cgr_graph_rs"
OUTPUT = CRATE_DIR / "THIRD_PARTY_LICENSES.md"
SQLITE_TEXT = REPO_ROOT / "scripts" / "license_texts" / "native" / "sqlite.txt"
ENCODING = "utf-8"

CARGO = "cargo"
FEATURES = ("--features", "python")
TREE_ARGS = (
    CARGO,
    "tree",
    "--edges",
    "normal,no-proc-macro",
    *FEATURES,
    "--target",
    "all",
    "--prefix",
    "none",
    "--format",
    "{p}|{l}",
)
METADATA_ARGS = (CARGO, "metadata", "--format-version", "1", *FEATURES)
TREE_LINE = re.compile(r"^(?P<name>\S+) v(?P<version>\S+)(?P<local> \(/[^)]*\))?")
DEDUPED_MARK = " (*)"

# The licence reproduced for a crate offering a choice, in order of
# preference: MIT is the shortest of the usual pairs and needs no NOTICE.
PREFERRED = ("MIT", "Zlib", "Apache-2.0")
LICENSE_FILES = {
    "MIT": ("LICENSE-MIT", "LICENSE-MIT.md", "LICENSE", "LICENSE.md"),
    "Zlib": ("LICENSE-ZLIB", "LICENSE-ZLIB.md", "LICENSE", "LICENSE.md"),
    "Apache-2.0": ("LICENSE-APACHE", "LICENSE-APACHE.md", "LICENSE", "LICENSE.md"),
}
LICENSE_SPLIT = re.compile(r"\s+OR\s+|/|[()]")
# `libsqlite3-sys`'s `bundled` feature compiles SQLite's own source in.
SQLITE_CRATE = "libsqlite3-sys"

HEADER = (
    "# Third-party licences\n\n"
    "`cgr-graph-rs` is compiled with the crates below. Each is listed with its\n"
    "declared licence and the text of the licence it is used under.\n\n"
    "Generated by `scripts/generate_rust_licenses.py` from `Cargo.lock`; do not\n"
    "edit by hand.\n"
)
SECTION = "\n## {name} {version}\n\nLicence: {declared} (used under {chosen})\n\n```text\n{text}\n```\n"
SQLITE_SECTION = (
    "\n## SQLite (compiled in by {crate})\n\nLicence: public domain\n\n"
    "```text\n{text}\n```\n"
)
ERR_NO_LICENSE = "{name} {version}: no licence among {wanted} in {expression!r}"
ERR_NO_TEXT = "{name} {version}: no {licence} file in {path}"
ERR_STALE = (
    "{path} does not match Cargo.lock; run `python scripts/generate_rust_licenses.py`"
)


@dataclass(frozen=True)
class Crate:
    name: str
    version: str
    licence: str


def _cargo(args: tuple[str, ...]) -> str:
    return subprocess.run(  # nosec B603 - fixed cargo argument list
        args, cwd=CRATE_DIR, check=True, capture_output=True, text=True
    ).stdout


def linked_crates() -> list[Crate]:
    """Every third-party crate compiled into the library, once each."""
    crates: dict[tuple[str, str], Crate] = {}
    for line in _cargo(TREE_ARGS).splitlines():
        package, _, licence = line.removesuffix(DEDUPED_MARK).partition("|")
        match = TREE_LINE.match(package)
        # The crate being built is this project's own, under its own licence.
        if match is None or match["local"]:
            continue
        key = (match["name"], match["version"])
        crates[key] = Crate(match["name"], match["version"], licence.strip())
    return sorted(crates.values(), key=lambda c: (c.name, c.version))


def source_dirs() -> dict[tuple[str, str], Path]:
    metadata = json.loads(_cargo(METADATA_ARGS))
    return {
        (p["name"], p["version"]): Path(p["manifest_path"]).parent
        for p in metadata["packages"]
    }


def chosen_licence(crate: Crate) -> str:
    offered = {part.strip() for part in LICENSE_SPLIT.split(crate.licence)}
    for licence in PREFERRED:
        if licence in offered:
            return licence
    raise SystemExit(
        ERR_NO_LICENSE.format(
            name=crate.name,
            version=crate.version,
            wanted=PREFERRED,
            expression=crate.licence,
        )
    )


def licence_text(crate: Crate, licence: str, source: Path) -> str:
    for name in LICENSE_FILES[licence]:
        path = source / name
        if path.is_file():
            return path.read_text(encoding=ENCODING).strip()
    raise SystemExit(
        ERR_NO_TEXT.format(
            name=crate.name, version=crate.version, licence=licence, path=source
        )
    )


def render() -> str:
    sources = source_dirs()
    parts = [HEADER]
    for crate in linked_crates():
        licence = chosen_licence(crate)
        text = licence_text(crate, licence, sources[(crate.name, crate.version)])
        parts.append(
            SECTION.format(
                name=crate.name,
                version=crate.version,
                declared=crate.licence,
                chosen=licence,
                text=text,
            )
        )
        if crate.name == SQLITE_CRATE:
            parts.append(
                SQLITE_SECTION.format(
                    crate=SQLITE_CRATE,
                    text=SQLITE_TEXT.read_text(encoding=ENCODING).strip(),
                )
            )
    return "".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if the file is out of date"
    )
    args = parser.parse_args(argv)
    rendered = render()
    if args.check:
        current = OUTPUT.read_text(encoding=ENCODING) if OUTPUT.is_file() else ""
        if current != rendered:
            print(ERR_STALE.format(path=OUTPUT.relative_to(REPO_ROOT)), file=sys.stderr)  # noqa: T201
            return 1
        return 0
    OUTPUT.write_text(rendered, encoding=ENCODING)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
